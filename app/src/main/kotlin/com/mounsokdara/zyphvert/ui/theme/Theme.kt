/**
 * AMOLED variant: pure black surfaces on top of the dark scheme.
 * Toggled from Settings once the data layer exists.
 */
fun amoledColorScheme(base: ColorScheme = DarkColors) = base.copy(
    background = Color.Black,
    surface = Color.Black,
    surfaceDim = Color.Black,
    surfaceContainerLowest = Color.Black,
    surfaceContainerLow = Color(0xFF0B0F0D),
    surfaceContainer = Color(0xFF111614),
    surfaceContainerHigh = Color(0xFF181D1B),
    surfaceContainerHighest = Color(0xFF202523),
)

@Composable
fun ZyphvertTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    amoled: Boolean = false,
    seedColor: Int = BrandSeed,
    content: @Composable () -> Unit
) {
    val base = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        // A color picked on the Theme page; the brand green keeps the hand-tuned palette.
        seedColor != BrandSeed -> remember(seedColor, darkTheme) { seedColorScheme(seedColor, darkTheme) }
        darkTheme -> DarkColors
        else -> LightColors
    }

    val colorScheme = if (darkTheme && amoled) amoledColorScheme(base) else base

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        shapes = Shapes,
        content = content
    )
}
